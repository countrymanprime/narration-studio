// Batch D1 screenshots: Production, Schedule (milestone dialog), Settings (Manuscript), project setup with the delivery profile.
import { launch, open, nav } from './lib.mjs'
const out = process.env.OUT || '../studio2-shots/D1'
const b = await launch()
for (const w of [1440, 1600, 1250]) {
  // Whole page: a tall window shows the full height of the content.
  let p = await open(b, 'app', { w, h: 900 })
  await p.screenshot({ path: `${out}/production-${w}.png` })
  await p.close()
  p = await open(b, 'app', { w, h: 1500 })
  await p.screenshot({ path: `${out}/production-${w}-tall.png` })
  await p.close()
  p = await open(b, 'app', { w, h: 900 })
  await nav(p, 'Schedule'); await p.mouse.move(w - 5, 400); await p.waitForTimeout(250)
  await p.screenshot({ path: `${out}/schedule-${w}.png` })
  await p.evaluate(() => document.querySelector('.ms-table')?.scrollIntoView({ block: 'end' }))
  await p.waitForTimeout(150)
  await p.screenshot({ path: `${out}/schedule-table-${w}.png` })
  await p.click('[data-msedit="3"]'); await p.waitForTimeout(250)
  await p.screenshot({ path: `${out}/schedule-dialog-${w}.png` })
  await p.keyboard.press('Escape')
  await p.close()
  p = await open(b, 'app', { w, h: 900 })
  await nav(p, 'Settings'); await p.mouse.move(w - 5, 400); await p.waitForTimeout(250)
  await p.screenshot({ path: `${out}/settings-top-${w}.png` })
  await p.evaluate(() => document.getElementById('repl')?.scrollIntoView({ block: 'center' }))
  await p.waitForTimeout(200)
  await p.screenshot({ path: `${out}/settings-manuscript-${w}.png` })
  await p.close()
  p = await open(b, 'app', { w, h: 900 })
  await p.click('#projbtn'); await p.click('#newp'); await p.waitForTimeout(400)
  await p.click('#imp0', { timeout: 3000 }).catch(() => {})
  await p.waitForTimeout(300)
  await p.click('#choose'); await p.waitForTimeout(300)
  await p.screenshot({ path: `${out}/setup-profile-${w}.png` })
  if (p.errors.length) console.log(w, 'errors', p.errors.filter((e) => !/CERT/.test(e)).slice(0, 3))
  await p.close()
}
await b.close()
