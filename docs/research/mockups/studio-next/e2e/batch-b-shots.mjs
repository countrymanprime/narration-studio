// Batch B screenshots: Production, Schedule, Booth footer, Pickups. node e2e/batch-b-shots.mjs  (APP_DIST=dist-X)
import { launch, open, nav } from './lib.mjs'
import path from 'node:path'
const OUT = path.resolve(process.env.SHOTS || '../studio2-shots/B')
const b = await launch()
for (const [w, h] of [[1440, 900], [1250, 800]]) {
  let p = await open(b, 'app', { w, h })
  const shot = async (name, full = false) => { await p.evaluate(() => (document.activeElement)?.blur?.()); await p.mouse.move(w - 5, 400); await p.waitForTimeout(400); await p.screenshot({ path: `${OUT}/${name}-${w}.png`, fullPage: full }) }
  await nav(p, 'Production')
  await shot('production')
  await p.evaluate(() => document.getElementById('main')?.scrollTo(0, 9999))
  await shot('production-bottom')
  await nav(p, 'Schedule')
  await p.evaluate(() => document.getElementById('main')?.scrollTo(0, 0))
  await shot('schedule-top')
  await p.evaluate(() => document.getElementById('main')?.scrollTo(0, 9999))
  await shot('schedule-bottom')
  await p.click('#mstpl')
  await shot('schedule-template-menu')
  await p.getByRole('option', { name: '15-minute checkpoint' }).click()
  await shot('schedule-template-filled')
  await p.close(); p = await open(b, 'app', { w, h })
  await nav(p, 'Booth')
  await shot('booth')
  await p.close(); p = await open(b, 'app', { w, h })
  await nav(p, 'Pickups')
  await shot('pickups')
  await p.click('#chk')
  await shot('pickups-check-dialog')
  await p.keyboard.press('Escape')
  await p.click('#mockbtn')
  await p.getByText('Nothing measured yet', { exact: true }).click()
  await p.mouse.click(5, 5)
  await nav(p, 'Production')
  await shot('production-unmeasured')
  await p.evaluate(() => document.getElementById('main')?.scrollTo(0, 9999))
  await shot('production-unmeasured-bottom')
  await nav(p, 'Schedule')
  await shot('schedule-unmeasured')
  await nav(p, 'Booth')
  await shot('booth-unmeasured')
  if (p.errors.length) console.log('errors', p.errors.slice(0, 5))
  await p.close()
}
await b.close()
