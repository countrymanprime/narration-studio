// Batch C2 screenshots: Proof, Pickups (+ Check dialog), Editing. node e2e/c2-shots.mjs  (APP_DIST=dist-X, SHOTS=dir)
import { launch, open, nav } from './lib.mjs'
import path from 'node:path'
const OUT = path.resolve(process.env.SHOTS || '../studio2-shots/C2')
const b = await launch()
const chapter = async (p, re) => { await p.click('#chapsel'); await p.locator('.pop').getByText(re).first().click(); await p.waitForTimeout(200) }
const mock = async (p, text) => { await p.click('#mockbtn'); await p.getByText(text, { exact: true }).first().click(); await p.keyboard.press('Escape'); await p.mouse.click(5, 5) }
for (const [w, h] of [[1440, 900], [1250, 800]]) {
  let p = await open(b, 'app', { w, h })
  const shot = async (name) => { await p.evaluate(() => (document.activeElement)?.blur?.()); await p.mouse.move(w - 5, 400); await p.waitForTimeout(400); await p.screenshot({ path: `${OUT}/${name}-${w}.png` }) }
  const fresh = async () => { await p.close(); p = await open(b, 'app', { w, h }) }
  // Proof
  await nav(p, 'Proof')
  await shot('proof-all')
  await p.click('[data-cs="5"]'); await p.waitForTimeout(300)
  await p.click('[data-wf]').catch(() => {})
  await p.click('tr[data-r="2"]'); await p.waitForTimeout(300)
  await shot('proof-chapter5')
  await p.click('#mockbtn'); await p.click('#mock-recheck'); await p.keyboard.press('Escape'); await p.mouse.click(5, 5); await p.waitForTimeout(300)
  await p.click('tr[data-r="2"]'); await p.waitForTimeout(300)
  await p.click('[data-d="waive"]'); await p.waitForTimeout(200)
  await shot('proof-stale-evidence')
  await p.click('#evaccept'); await p.fill('#pdnote', 'Checked the new reading'); await p.click('[data-d="waive"]'); await p.waitForTimeout(300)
  await p.click('tr[data-r="2"]'); await p.waitForTimeout(300)
  await shot('proof-history')
  await p.locator('#psort').click(); await p.getByRole('option', { name: 'By confidence' }).click(); await p.waitForTimeout(300)
  await shot('proof-sorted')
  // Pickups
  await fresh()
  await nav(p, 'Pickups')
  await shot('pickups')
  await p.click('#chk'); await p.waitForTimeout(400)
  await shot('pickups-check-dialog')
  await p.click('#ck-run'); await p.waitForTimeout(3500)
  await shot('pickups-after-check')
  await p.click('#chk'); await p.waitForTimeout(400)
  await shot('pickups-check-dialog-results')
  // Editing
  await fresh()
  await nav(p, 'Editing')
  await chapter(p, /Advice from a Caterpillar/)
  await p.click('[role="tab"][data-tab="takes"]')
  await p.click('tr[data-ps="ps5-9"]'); await p.waitForTimeout(300)
  await shot('editing-suggestion')
  await p.click('[data-prep="normalise"]'); await p.waitForTimeout(300)
  await p.click('[data-prep="trim-silence"]'); await p.waitForTimeout(300)
  await shot('editing-suggestion-prepared')
  await p.click('[data-tkeep="T05-9"]'); await p.waitForTimeout(300)
  await p.click('#thide'); await p.waitForTimeout(300)
  await shot('editing-hidden')
  await p.click('tr[data-ps="ps5-15"]'); await p.waitForTimeout(300)
  await shot('editing-duplicate')
  await p.click('#tsplit'); await p.waitForTimeout(300)
  await shot('editing-split')
  // Audacity with backups
  await fresh()
  await mock(p, 'Audacity (recordings live in the DAW)')
  await nav(p, 'Editing')
  await chapter(p, /Advice from a Caterpillar/)
  await p.click('[role="tab"][data-tab="backups"]'); await p.waitForTimeout(300)
  await shot('editing-audacity-backups-off')
  await p.getByText('Keep backups', { exact: true }).click(); await p.waitForTimeout(200)
  await nav(p, 'Booth')
  await chapter(p, /Advice from a Caterpillar/)
  await p.evaluate(() => document.activeElement?.blur?.())
  await p.keyboard.press('Space'); await p.waitForTimeout(600)
  await p.keyboard.press('r'); await p.waitForTimeout(400)
  await p.keyboard.press('Space'); await p.waitForTimeout(400)
  await p.keyboard.press('Escape'); await p.waitForTimeout(400)
  await nav(p, 'Editing')
  await chapter(p, /Advice from a Caterpillar/)
  await p.click('[role="tab"][data-tab="backups"]'); await p.waitForTimeout(300)
  await shot('editing-audacity-backups')
  await p.click('[role="tab"][data-tab="takes"]'); await p.waitForTimeout(300)
  await shot('editing-audacity-takes')
  console.log(w, p.errors.filter((e) => !/ERR_CERT/.test(e)))
  await p.close()
}
await b.close()
