// Batch A screenshots: Story Bible and Script. node e2e/batch-a-shots.mjs  (APP_DIST=dist-X)
import { launch, open, nav } from './lib.mjs'
import path from 'node:path'
const OUT = path.resolve(process.env.SHOTS || '../studio2-shots/A')
const b = await launch()
for (const [w, h] of [[1440, 900], [1250, 800]]) {
  const t = `${w}`
  const p = await open(b, 'app', { w, h })
  const shot = async (name) => { await p.waitForTimeout(250); await p.screenshot({ path: `${OUT}/${name}-${t}.png` }) }
  await nav(p, 'Story Bible')
  await p.click('[data-sbe="the-gardeners"]')
  await shot('bible-read')
  await p.click('#sbedit')
  await p.fill('input[aria-label="How I say Seven"]', 'SEV-un')
  await shot('bible-edit')
  await p.click('[aria-label^="Pronunciation source for Seven"]')
  await shot('bible-source-menu')
  await p.keyboard.press('Escape')
  await p.fill('#sbaka', 'Duchess')
  await p.press('#sbaka', 'Enter')
  await shot('bible-merge-offer')
  await p.click('#sbcancel')
  await p.click('#sbreview')
  await shot('bible-needs-review')
  await p.click('#sbreview')
  await p.click('#sbsort')
  await shot('bible-sort-menu')
  await p.keyboard.press('Escape')
  await p.click('#sbnew')
  await shot('bible-new-draft')
  await p.click('#sbcancel')
  await p.click('[data-sbe="queen-of-hearts"]')
  await p.evaluate(() => document.querySelector('#sbpg section:last-child')?.scrollTo(0, 9999))
  await shot('bible-appears-in')
  await nav(p, 'Script')
  await p.waitForTimeout(300)
  await shot('script-reader')
  if (w <= 1280) await p.click('[data-drawer="rail"]')
  const tab = p.locator('[role=tab]', { hasText: 'Words' }).first()
  if (await tab.count()) await tab.click()
  const row = p.locator('tr[data-w="croquet"]')
  if (await row.count()) await row.click()
  await shot('script-words')
  if (p.errors.length) console.log(t, 'errors:', p.errors.slice(0, 5))
  await p.context().close()
}
await b.close()
