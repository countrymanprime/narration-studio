// Builds docs/adr/topics.md, the ADRs grouped by topic, from the ADR files and scripts/ci/adr-topics.json, so a plan can find the
// decisions that govern a change without reading the whole index.
//
// An ADR sits under exactly one topic: the first topic (in file order) that pins its number, else the first whose `match` hits its
// title. An ADR no topic claims fails the check, so a new ADR either hits a pattern or is pinned. Status is read from the ADR as
// scripts/ci/adr-index.mjs reads it.
//
//   node scripts/ci/adr-topics.mjs                  exits 1 when docs/adr/topics.md is stale or an ADR has no topic
//   node scripts/ci/adr-topics.mjs --write          rewrites docs/adr/topics.md
//   node scripts/ci/adr-topics.mjs --topic <id>     prints one topic's ADRs (for an agent that does not open the page)
//   node scripts/ci/adr-topics.mjs --grep <words>   prints the ADRs whose title has every word
//   node scripts/ci/adr-topics.mjs --report         prints the topic sizes and the unclaimed ADRs

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ADR_DIR, readAdrs } from './adr-index.mjs';
import { REPO_ROOT } from './layout.mjs';

export const TOPICS_FILE = 'docs/adr/topics.md';
export const TOPICS_CONFIG = 'scripts/ci/adr-topics.json';

/** The status word the topic page shows: the first word, so "Accepted (amended by ...)" groups with Accepted. */
export function statusWord(status) {
  return status.split(/[\s(]/)[0] || status;
}

/** Compiles a config's topics once: each pattern list becomes case-insensitive regular expressions. */
export function compileTopics(config) {
  return config.topics.map((topic) => ({
    ...topic,
    patterns: (topic.match ?? []).map((pattern) => new RegExp(pattern, 'i')),
    pinned: new Set(topic.pins ?? []),
  }));
}

/** The id of the topic that claims `adr`, or undefined. A pin beats a pattern, and the first topic in file order wins. */
export function topicOf(adr, topics) {
  const pinned = topics.find((topic) => topic.pinned.has(adr.number));
  if (pinned) return pinned.id;
  return topics.find((topic) => topic.patterns.some((pattern) => pattern.test(adr.title)))?.id;
}

/** Groups ADRs by topic id (in config order) and returns the ones no topic claims. */
export function groupAdrs(adrs, topics) {
  const groups = new Map(topics.map((topic) => [topic.id, []]));
  const unclaimed = [];
  for (const adr of [...adrs].sort((a, b) => a.number.localeCompare(b.number))) {
    const id = topicOf(adr, topics);
    if (id) groups.get(id).push(adr);
    else unclaimed.push(adr);
  }
  return { groups, unclaimed };
}

/** A pin that names no ADR, or an id used twice, is a config mistake. */
export function configProblems(topics, adrs) {
  const problems = [];
  const numbers = new Set(adrs.map((adr) => adr.number));
  const seen = new Set();
  for (const topic of topics) {
    if (seen.has(topic.id)) problems.push(`topic id ${topic.id} is used twice`);
    seen.add(topic.id);
    for (const pin of topic.pinned) if (!numbers.has(pin)) problems.push(`${topic.id} pins ${pin}, which is not an ADR`);
  }
  return problems;
}

/** topics.md. */
export function renderTopics(adrs, topics) {
  const { groups } = groupAdrs(adrs, topics);
  const lines = [
    '<!-- Generated by scripts/ci/adr-topics.mjs --write from the ADR files and scripts/ci/adr-topics.json. Do not edit. -->',
    '',
    '# ADRs by topic',
    '',
    'The decisions in [the index](README.md) grouped by what they govern, so a plan can find the ones that apply to a change. Each ADR is under one topic. A **Proposed** ADR describes what the code does but the owner has not accepted it: treat it as the current behaviour, and say so when relying on it. To find an ADR by word, run `node scripts/ci/adr-topics.mjs --grep <words>`.',
    '',
    '| Topic | ADRs |',
    '| --- | --- |',
    ...topics.map((topic) => `| [${topic.title}](#${topic.id}) | ${groups.get(topic.id).length} |`),
  ];
  for (const topic of topics) {
    lines.push('', `<a id="${topic.id}"></a>`, '', `## ${topic.title}`, '', topic.summary, '', '| # | Decision | Status |', '| --- | --- | --- |');
    for (const adr of groups.get(topic.id)) lines.push(`| [${adr.number}](${adr.file}) | ${adr.title} | ${statusWord(adr.status)} |`);
  }
  return `${lines.join('\n')}\n`;
}

function load() {
  const adrs = readAdrs(join(REPO_ROOT, ADR_DIR));
  const topics = compileTopics(JSON.parse(readFileSync(join(REPO_ROOT, TOPICS_CONFIG), 'utf8')));
  return { adrs, topics };
}

function main(argv) {
  const { adrs, topics } = load();
  const { groups, unclaimed } = groupAdrs(adrs, topics);
  const argAfter = (flag) => argv[argv.indexOf(flag) + 1];

  if (argv.includes('--report')) {
    for (const topic of topics) console.log(String(groups.get(topic.id).length).padStart(4), topic.id);
    console.log(`unclaimed: ${unclaimed.length}`);
    for (const adr of unclaimed) console.log(`  ${adr.number} ${adr.title}`);
    return 0;
  }
  if (argv.includes('--topic')) {
    const id = argAfter('--topic');
    if (!groups.has(id)) {
      console.error(`No topic ${id}. Topics: ${topics.map((t) => t.id).join(', ')}`);
      return 1;
    }
    for (const adr of groups.get(id)) console.log(`${adr.number}  ${statusWord(adr.status).padEnd(10)} ${adr.title}`);
    return 0;
  }
  if (argv.includes('--grep')) {
    const words = argv.slice(argv.indexOf('--grep') + 1).map((word) => word.toLowerCase());
    for (const adr of adrs) {
      const title = adr.title.toLowerCase();
      if (words.every((word) => title.includes(word))) console.log(`${adr.number}  ${statusWord(adr.status).padEnd(10)} ${adr.title}`);
    }
    return 0;
  }

  const problems = configProblems(topics, adrs);
  if (unclaimed.length) problems.push(...unclaimed.map((adr) => `no topic claims ADR ${adr.number}: add a pattern or a pin in ${TOPICS_CONFIG}`));
  if (problems.length) {
    for (const problem of problems) console.error(problem);
    return 1;
  }
  const path = join(REPO_ROOT, TOPICS_FILE);
  const next = renderTopics(adrs, topics);
  let current = '';
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    // Missing file: treated as stale below.
  }
  if (argv.includes('--write')) {
    if (next !== current) writeFileSync(path, next);
    console.log(next === current ? `${TOPICS_FILE} is current.` : `${TOPICS_FILE} was rewritten.`);
    return 0;
  }
  if (next !== current) {
    console.error(`${TOPICS_FILE} is stale. Run: node scripts/ci/adr-topics.mjs --write`);
    return 1;
  }
  console.log(`${TOPICS_FILE} is current.`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
