import assert from 'node:assert/strict';
import test from 'node:test';

import { commitsOf, evaluateHeartbeat, failedJobs, isHoldTicked, parseLastPass, redReport, tickHold, tierOf, TIERS, trainIssues } from './train-health.mjs';

const HOUR = 60 * 60 * 1000;
const now = new Date('2026-10-10T12:00:00Z');
const bodyAt = (stamp, hold = ' ') => `## Train control\n\nLast pass: ${stamp}\n\n### Switches\n\n- [${hold}] HOLD\n- [ ] DRAIN\n`;

test('parseLastPass reads the ISO timestamp on the Last pass line', () => {
  assert.equal(parseLastPass(bodyAt('2026-10-10T11:30:00Z'))?.toISOString(), '2026-10-10T11:30:00.000Z');
});

test('parseLastPass ignores a body with no Last pass line or an unreadable date', () => {
  assert.equal(parseLastPass('## Train control\n\nLast rewritten 2026-09-27 20:42 UTC.'), undefined);
  assert.equal(parseLastPass('Last pass: yesterday-ish'), undefined);
});

test('isHoldTicked sees a ticked HOLD and not DRAIN', () => {
  assert.equal(isHoldTicked(bodyAt('2026-10-10T11:30:00Z', 'x')), true);
  assert.equal(isHoldTicked('- [ ] HOLD\n- [x] DRAIN\n'), false);
  assert.equal(isHoldTicked('- [x] HOLD-UNTIL-RESET\n'), false);
});

test('evaluateHeartbeat: a recent pass is healthy', () => {
  assert.equal(evaluateHeartbeat({ body: bodyAt('2026-10-10T11:00:00Z'), now, staleAfterMs: 2 * HOUR }).stale, false);
});

test('evaluateHeartbeat: a pass older than the threshold is stale and says how long', () => {
  const result = evaluateHeartbeat({ body: bodyAt('2026-10-10T08:00:00Z'), now, staleAfterMs: 2 * HOUR });
  assert.equal(result.stale, true);
  assert.equal(result.lastPass.toISOString(), '2026-10-10T08:00:00.000Z');
  assert.match(result.reason, /4 h/);
});

test('evaluateHeartbeat: no Last pass line is stale, because the coordinator has never reported one', () => {
  const result = evaluateHeartbeat({ body: '## Train control\n', now, staleAfterMs: 2 * HOUR });
  assert.equal(result.stale, true);
  assert.match(result.reason, /no Last pass/);
});

test('evaluateHeartbeat: an owner HOLD is not a stall', () => {
  const result = evaluateHeartbeat({ body: bodyAt('2026-10-01T00:00:00Z', 'x'), now, staleAfterMs: 2 * HOUR });
  assert.equal(result.stale, false);
  assert.match(result.reason, /HOLD/);
});

test('tickHold ticks the HOLD box and nothing else', () => {
  const ticked = tickHold(bodyAt('2026-10-10T11:00:00Z'));
  assert.match(ticked, /- \[x\] HOLD\n- \[ \] DRAIN/);
});

test('tickHold leaves an already ticked body unchanged and does not touch HOLD-UNTIL-RESET', () => {
  const already = bodyAt('2026-10-10T11:00:00Z', 'x');
  assert.equal(tickHold(already), already);
  const other = '- [ ] HOLD-UNTIL-RESET\n';
  assert.equal(tickHold(other), other);
});

test('trainIssues lists every open train issue from gh issue list output', () => {
  assert.deepEqual(trainIssues('[{"number":3200},{"number":3201}]'), ['3200', '3201']);
});

test('trainIssues watches nothing when no train issue is open', () => {
  assert.deepEqual(trainIssues('[]'), []);
  assert.deepEqual(trainIssues(''), []);
});

test('trainIssues takes TRAIN_ISSUE over the list, for a manual run', () => {
  assert.deepEqual(trainIssues('[{"number":3200}]', '3205'), ['3205']);
});

test('failedJobs names the jobs that failed, were cancelled or timed out, and no skipped or green one', () => {
  const jobs = [
    { name: 'quality / lint', conclusion: 'success' },
    { name: 'quality / Test (Linux 4/6)', conclusion: 'failure' },
    { name: 'quality / Test (Windows 2/2)', conclusion: 'timed_out' },
    { name: 'quality / Build (Windows)', conclusion: 'cancelled' },
    { name: 'Tick HOLD when main is red', conclusion: 'skipped' },
    { name: 'CI passed', conclusion: null },
  ];
  assert.deepEqual(failedJobs(jobs), ['quality / Test (Linux 4/6)', 'quality / Test (Windows 2/2)', 'quality / Build (Windows)']);
  assert.deepEqual(failedJobs(undefined), []);
});

test('commitsOf reads each commit as its sha and the first line of its message', () => {
  const compare = JSON.stringify({ commits: [{ sha: 'a'.repeat(40), commit: { message: 'fix(ui): one\n\nbody' } }] });
  assert.deepEqual(commitsOf(compare), [{ sha: 'a'.repeat(40), title: 'fix(ui): one' }]);
  assert.deepEqual(commitsOf(''), []);
});

test('redReport names the run, the failed jobs and the commits since the last green run, and says what may merge', () => {
  const report = redReport({
    runUrl: 'https://example.test/runs/1',
    sha: '0123456789abcdef',
    failed: ['quality / Test (Linux 4/6)'],
    commits: [{ sha: 'fedcba9876543210', title: 'feat(booth): two' }],
  });
  assert.match(report, /failed at 0123456: https:\/\/example\.test\/runs\/1/);
  assert.match(report, /- `quality \/ Test \(Linux 4\/6\)`/);
  assert.match(report, /- fedcba9 feat\(booth\): two/);
  assert.match(report, /merge only the fix or the revert/);
  assert.match(report, /Generated by \[Claude Code\]/);
});

test('redReport says what it could not read, so a failed read never hides the red run', () => {
  const report = redReport({ runUrl: 'u', sha: '0123456789', failed: [], commits: [] });
  assert.match(report, /Failed jobs:\n- not read: see the run/);
  assert.match(report, /- not read: no earlier green run was found/);
});

test('the slow-clock tier report names the failed jobs and the fix, lists no commits and holds nothing', () => {
  const report = redReport({ runUrl: 'https://example.test/run/9', sha: '0123456789abcdef', failed: ['slow-clock'], commits: [], tier: 'slow-clock' });
  assert.match(report, /slowed to 70% at 0123456: https:\/\/example\.test\/run\/9/);
  assert.match(report, /- `slow-clock`/);
  assert.match(report, /pastStartGuard/);
  assert.match(report, /Nothing is held/);
  assert.doesNotMatch(report, /Commits on `main`/);
});

test('each tier has its own label, so one tier\'s green run never closes another tier\'s issue', () => {
  assert.equal(tierOf().label, 'main-red');
  assert.equal(tierOf('main'), TIERS.main);
  assert.equal(tierOf('slow-clock').label, 'slow-clock-red');
  assert.notEqual(tierOf('main').label, tierOf('slow-clock').label);
});

test('a tier names its issue by the commit, and only main lists the commits since the last green run', () => {
  assert.match(tierOf('main').title('0123456789'), /^main is red: .* at 0123456$/);
  assert.match(tierOf('slow-clock').title('0123456789'), /slowed page clock at 0123456$/);
  assert.equal(tierOf('main').commits, true);
  assert.equal(tierOf('slow-clock').commits, false);
});

test('an unknown tier is refused, not taken for main', () => {
  assert.throws(() => tierOf('nightly'), /unknown tier nightly: one of main, slow-clock/);
});
