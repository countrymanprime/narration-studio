import assert from 'node:assert/strict';
import test from 'node:test';

import { AREAS, FOOTER, classifyArea, fetchSlices, guardedGh, parseOwnerSteps, renderReport } from '../dev/owner-qa-list.mjs';

const body = (line, extra = '') => `Part of #1024.\n\n\`\`\`text\nPRD: studio-next-roll.prd.md, slice SND-6a (Phase 2)\nScreenshots: none\n${line}\nADRs: none\nEstimate (pw): 0.3\n\`\`\`\n${extra}`;

test('extracts-owner-steps-from-a-slice-body', () => {
  const parsed = parseOwnerSteps(body('Owner steps (to #992): In-REAPER check of roll_start on a project copy'));
  assert.deepEqual(parsed, { status: 'steps', steps: ['In-REAPER check of roll_start on a project copy'] });
});

test('extracts-owner-steps-from-a-slice-body: none gives no step, with or without a note', () => {
  assert.deepEqual(parseOwnerSteps(body('Owner steps (to #992): none')), { status: 'none', steps: [] });
  assert.deepEqual(parseOwnerSteps(body('Owner steps (to #992): none (the pass is on #992 already)')), { status: 'none', steps: [] });
});

test('handles-the-wrapped-and-numbered-forms: a wrapped step', () => {
  const parsed = parseOwnerSteps(body('Owner steps (to #992): record with the pedal\n  and compare the take count;\n  then undo'));
  assert.deepEqual(parsed.steps, ['record with the pedal and compare the take count; then undo']);
});

test('handles-the-wrapped-and-numbered-forms: a (1) (2) list', () => {
  const parsed = parseOwnerSteps(body('Owner steps (to #992): (1) approve this PR: it edits the procedure; (2) decide whether the workflows read #989'));
  assert.deepEqual(parsed.steps, ['approve this PR: it edits the procedure', 'decide whether the workflows read #989']);
});

test('handles-the-wrapped-and-numbered-forms: a quoted template before the real field does not count', () => {
  const quoted = '> Owner steps (to #992): <what only the owner can do>\n\n';
  const parsed = parseOwnerSteps(`${quoted}${body('Owner steps (to #992): press Shift+F10 in the built app')}`);
  assert.deepEqual(parsed.steps, ['press Shift+F10 in the built app']);
});

test('handles-the-wrapped-and-numbered-forms: the field twice in a body, the last unquoted one wins', () => {
  const twice = `${body('Owner steps (to #992): none')}\nOwner steps (to #992): run the Audacity pass`;
  assert.deepEqual(parseOwnerSteps(twice).steps, ['run the Audacity pass']);
});

test('no-step-is-silently-dropped: a body with no parsable field is unparsed', () => {
  assert.equal(parseOwnerSteps('no field here').status, 'unparsed');
  assert.equal(parseOwnerSteps(body('Owner steps (to #992):')).status, 'unparsed');
  assert.equal(parseOwnerSteps(body('Owner steps (to #992): <what only the owner can do>')).status, 'unparsed');
});

test('groups-by-area: classifies by what the owner must have in hand', () => {
  assert.equal(classifyArea('Shift+F10 in the Wails WebView of the built app'), 'app');
  assert.equal(classifyArea('In-REAPER check of stack_takes'), 'reaper');
  assert.equal(classifyArea('Audacity pass for backups'), 'audacity');
  assert.equal(classifyArea('a real record with the foot pedal'), 'hardware');
  assert.equal(classifyArea('extraction on a real manuscript'), 'manuscript');
  assert.equal(classifyArea('rule on any waived gap'), 'other');
  assert.ok(Object.keys(AREAS).includes('other'));
});

const slice = (number, text, extra = {}) => ({ number, state: 'open', title: `SN-X${number} t`, body: `\`\`\`slice-meta\nid: SN-X${number}\n\`\`\`\n${text}`, ...extra });

test('groups-by-area: each step carries its slice id and PRD code and the report groups them', () => {
  const issues = [
    slice(1, body('Owner steps (to #992): In-REAPER check of roll_start')),
    slice(2, body('Owner steps (to #992): Audacity pass for backups (docs/operations/audacity-verification-pass.md)')),
    slice(3, body('Owner steps (to #992): none')),
  ];
  const report = renderReport(issues, { baseline: false });
  assert.match(report, /## REAPER/);
  assert.match(report, /## Audacity 3/);
  assert.ok(report.indexOf('## REAPER') < report.indexOf('## Audacity 3'));
  assert.match(report, /SN-X1/);
  assert.match(report, /SND/);
  assert.match(report, /\[audacity-verification-pass\.md\]|audacity-verification-pass\.md/);
  assert.doesNotMatch(report, /SN-X3/);
});

test('report-is-markdown-for-a-comment: each step has run, pass, fail and issue-to-open, and the footer ends it', () => {
  const report = renderReport([slice(1, body('Owner steps (to #992): In-REAPER check of roll_start'))], { baseline: false });
  for (const label of ['**Run:**', '**Pass:**', '**Fail:**', '**On a fail:**']) assert.ok(report.includes(label), label);
  assert.ok(report.trimEnd().endsWith(FOOTER.trim()));
  assert.match(FOOTER, /\n---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_/);
});

test('report includes the baseline owner steps the PRDs name, linked to their runbooks', () => {
  const report = renderReport([], {});
  assert.match(report, /Shift\+F10/);
  assert.match(report, /studio-next-daw-spike-runbook\.md/);
  assert.match(report, /reaper-verification-pass\.md/);
});

test('no-step-is-silently-dropped: an unparsable body is listed under needs a human read with its number', () => {
  const report = renderReport([slice(77, 'nothing useful')], { baseline: false });
  assert.match(report, /## Needs a human read/);
  assert.match(report, /#77/);
});

test('read-only: guardedGh refuses anything but a GET api route', () => {
  const calls = [];
  const run = (args) => (calls.push(args), '[]');
  const gh = guardedGh(run);
  gh(['api', 'repos/o/r/issues?page=1']);
  assert.equal(calls.length, 1);
  for (const bad of [['api', '-X', 'POST', 'x'], ['api', '--method', 'PATCH', 'x'], ['api', '-f', 'a=b', 'x'], ['api', '--input', 'f', 'x'], ['issue', 'comment', '1'], ['api', '-F', 'a=b', 'x']]) {
    assert.throws(() => gh(bad), /read-only/);
  }
  assert.equal(calls.length, 1);
});

test('read-only: fetchSlices pages through GET routes and skips pull requests', () => {
  const seen = [];
  const run = (args) => {
    seen.push(args);
    const page = Number(/&page=(\d+)/.exec(args[1])[1]);
    if (page === 1) return JSON.stringify(Array.from({ length: 100 }, (_, i) => ({ number: i + 1, body: '' })));
    return JSON.stringify([{ number: 200, body: '' }, { number: 201, body: '', pull_request: {} }]);
  };
  const issues = fetchSlices(guardedGh(run));
  assert.equal(issues.length, 101);
  assert.ok(seen.every((a) => a[0] === 'api' && !a.includes('-X')));
});
