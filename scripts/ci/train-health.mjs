#!/usr/bin/env node
// Watches the agent train from outside it (.claude/skills/agent-train/SKILL.md, "Safety net").
//
// node scripts/ci/train-health.mjs heartbeat       Warns on #510 when #509's `Last pass:` line is older than 2 hours.
// node scripts/ci/train-health.mjs hold <reason>   Ticks HOLD on #509 and says why, so nothing launches until the owner clears it.
//
// The coordinator rewrites `Last pass: <ISO UTC>` on #509 at the end of every pass, so a stale line means the Routine
// has stopped (a spent credit, a failed session, a deleted trigger). `hold` is what the nightly main check runs when
// `main` is red. Both need the `gh` CLI and GH_TOKEN with issues: write.

import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const TRAIN_ISSUE = process.env.TRAIN_ISSUE ?? '509';
const OWNER_QUEUE_ISSUE = process.env.OWNER_QUEUE_ISSUE ?? '510';
const STALE_AFTER_MS = 2 * 60 * 60 * 1000;
const HEARTBEAT_MARKER = '<!-- train-heartbeat -->';
const SIGNATURE = '---\n_Generated by [Claude Code](https://claude.ai/code)_';

const LAST_PASS_LINE = /^Last pass:[ \t]*(\S+)[ \t]*$/m;
const HOLD_BOX = /^(- \[)[ xX](\] HOLD[ \t]*)$/m;

/** The time on the `Last pass:` line, or undefined when the line is missing or not a date. */
export function parseLastPass(body) {
  const stamp = LAST_PASS_LINE.exec(body ?? '')?.[1];
  const parsed = stamp ? new Date(stamp) : undefined;
  return parsed && !Number.isNaN(parsed.getTime()) ? parsed : undefined;
}

/** Whether the owner's HOLD switch is ticked. `HOLD-UNTIL-RESET` and `DRAIN` are different switches. */
export function isHoldTicked(body) {
  return /^- \[[xX]\] HOLD[ \t]*$/m.test(body ?? '');
}

/** Judges the train by its last pass. A ticked HOLD is the owner's stop, not a stall. */
export function evaluateHeartbeat({ body, now, staleAfterMs = STALE_AFTER_MS }) {
  if (isHoldTicked(body)) return { stale: false, reason: 'HOLD is ticked, so no pass is expected' };
  const lastPass = parseLastPass(body);
  if (!lastPass) return { stale: true, reason: 'the body has no Last pass line, so the coordinator has never reported one' };
  const age = now.getTime() - lastPass.getTime();
  if (age <= staleAfterMs) return { stale: false, lastPass, reason: 'a pass ran recently' };
  return { stale: true, lastPass, reason: `the last pass was ${Math.round(age / 3_600_000)} h ago (limit ${staleAfterMs / 3_600_000} h)` };
}

/** The body with the HOLD box ticked. An already ticked body comes back unchanged. */
export function tickHold(body) {
  return body.replace(HOLD_BOX, '$1x$2');
}

function gh(args, input) {
  return execFileSync('gh', args, { encoding: 'utf8', input, maxBuffer: 16 * 1024 * 1024 });
}

function readIssue(number, fields) {
  return JSON.parse(gh(['issue', 'view', number, '--json', fields]));
}

function heartbeat() {
  const { body } = readIssue(TRAIN_ISSUE, 'body');
  const verdict = evaluateHeartbeat({ body, now: new Date() });
  if (!verdict.stale) {
    console.log(`train healthy: ${verdict.reason}`);
    return;
  }
  const warnings = readIssue(OWNER_QUEUE_ISSUE, 'comments').comments.filter((c) => c.body.includes(HEARTBEAT_MARKER));
  const latest = warnings.at(-1);
  // One warning per stall: a warning newer than the last pass has already told the owner.
  if (latest && (!verdict.lastPass || new Date(latest.createdAt) > verdict.lastPass)) {
    console.log(`train stalled (${verdict.reason}); already reported on #${OWNER_QUEUE_ISSUE}`);
    return;
  }
  const message = `${HEARTBEAT_MARKER}\n**The agent train has stalled:** ${verdict.reason}.\n\nCheck the coordinator Routine (usage, credit, the trigger itself), then read #${TRAIN_ISSUE}. The coordinator clears this by writing a fresh \`Last pass:\` line.\n\n${SIGNATURE}`;
  gh(['issue', 'comment', OWNER_QUEUE_ISSUE, '--body-file', '-'], message);
  console.log(`train stalled (${verdict.reason}); reported on #${OWNER_QUEUE_ISSUE}`);
}

function hold(reason) {
  if (!reason) throw new Error('hold needs a reason');
  const { body } = readIssue(TRAIN_ISSUE, 'body');
  if (!isHoldTicked(body)) gh(['issue', 'edit', TRAIN_ISSUE, '--body-file', '-'], tickHold(body));
  gh(['issue', 'comment', TRAIN_ISSUE, '--body-file', '-'], `**HOLD ticked by the main health check:** ${reason}\n\nThe owner or the coordinator clears it once \`main\` is green again.\n\n${SIGNATURE}`);
  console.log(`HOLD ticked on #${TRAIN_ISSUE}: ${reason}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [command, ...rest] = process.argv.slice(2);
  if (command === 'heartbeat') heartbeat();
  else if (command === 'hold') hold(rest.join(' ').trim());
  else {
    console.error('usage: train-health.mjs heartbeat | hold <reason>');
    process.exit(2);
  }
}
