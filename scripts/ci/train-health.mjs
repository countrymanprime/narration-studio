#!/usr/bin/env node
// Watches the agent train from outside it (.claude/skills/agent-train/references/coordinator.md, "Safety net").
//
// node scripts/ci/train-health.mjs heartbeat       Warns on each open train issue whose `Last pass:` line is older than 2 hours.
// node scripts/ci/train-health.mjs hold <reason>   Ticks HOLD on each open train issue and says why, so nothing launches until
//                                                  the owner clears it.
//
// A train issue is an open issue labelled `agent-train`; each train has one, and its coordinator rewrites
// `Last pass: <ISO UTC>` in its body at the end of every pass, so a stale line means that train's Routine has stopped (a
// spent credit, a failed session, a deleted trigger). The warning goes on the same issue, whose Owner queue the owner
// reads. `TRAIN_ISSUE` names one issue instead, for a manual run. `hold` is what the main health check runs when `main`
// is red. Both need the `gh` CLI and GH_TOKEN with issues: write.

import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const TRAIN_LABEL = 'agent-train';
const STALE_AFTER_MS = 2 * 60 * 60 * 1000;
const HEARTBEAT_MARKER = '<!-- train-heartbeat -->';
const SIGNATURE = '---\n_Generated by [Claude Code](https://claude.ai/code)_';

const LAST_PASS_LINE = /^Last pass:[ \t]*(\S+)[ \t]*$/m;
const HOLD_BOX = /^(- \[)[ xX](\] HOLD[ \t]*)$/m;

/** The time on the `Last pass:` line, or undefined when the line is missing or not a date. */
export function parseLastPass(body) {
  const stamp = LAST_PASS_LINE.exec(body ?? '')?.[1];
  const parsed = stamp ? new Date(stamp) : undefined;
  return parsed && !Number.isNaN(parsed.getTime()) ? parsed : undefined;
}

/** Whether the owner's HOLD switch is ticked. `HOLD-UNTIL-RESET` and `DRAIN` are different switches. */
export function isHoldTicked(body) {
  return /^- \[[xX]\] HOLD[ \t]*$/m.test(body ?? '');
}

/** Judges the train by its last pass. A ticked HOLD is the owner's stop, not a stall. */
export function evaluateHeartbeat({ body, now, staleAfterMs = STALE_AFTER_MS }) {
  if (isHoldTicked(body)) return { stale: false, reason: 'HOLD is ticked, so no pass is expected' };
  const lastPass = parseLastPass(body);
  if (!lastPass) return { stale: true, reason: 'the body has no Last pass line, so the coordinator has never reported one' };
  const age = now.getTime() - lastPass.getTime();
  if (age <= staleAfterMs) return { stale: false, lastPass, reason: 'a pass ran recently' };
  return { stale: true, lastPass, reason: `the last pass was ${Math.round(age / 3_600_000)} h ago (limit ${staleAfterMs / 3_600_000} h)` };
}

/** The body with the HOLD box ticked. An already ticked body comes back unchanged. */
export function tickHold(body) {
  return body.replace(HOLD_BOX, '$1x$2');
}

/** The issue numbers to watch: `TRAIN_ISSUE` when set, else every open issue in `gh issue list --json number` output. */
export function trainIssues(listJson, override) {
  if (override) return [String(override)];
  return JSON.parse(listJson || '[]').map((issue) => String(issue.number));
}

function gh(args, input) {
  return execFileSync('gh', args, { encoding: 'utf8', input, maxBuffer: 16 * 1024 * 1024 });
}

function readIssue(number, fields) {
  return JSON.parse(gh(['issue', 'view', number, '--json', fields]));
}

function openTrainIssues() {
  const list = process.env.TRAIN_ISSUE
    ? ''
    : gh(['issue', 'list', '--label', TRAIN_LABEL, '--state', 'open', '--json', 'number', '--limit', '50']);
  const issues = trainIssues(list, process.env.TRAIN_ISSUE);
  if (issues.length === 0) console.log(`no open issue labelled ${TRAIN_LABEL}: no train to watch`);
  return issues;
}

function heartbeatOne(issue) {
  const { body, comments } = readIssue(issue, 'body,comments');
  const verdict = evaluateHeartbeat({ body, now: new Date() });
  if (!verdict.stale) {
    console.log(`#${issue} healthy: ${verdict.reason}`);
    return;
  }
  const latest = comments.filter((c) => c.body.includes(HEARTBEAT_MARKER)).at(-1);
  // One warning per stall: a warning newer than the last pass has already told the owner.
  if (latest && (!verdict.lastPass || new Date(latest.createdAt) > verdict.lastPass)) {
    console.log(`#${issue} stalled (${verdict.reason}); already reported`);
    return;
  }
  const message = `${HEARTBEAT_MARKER}\n**This train has stalled:** ${verdict.reason}.\n\nCheck the coordinator Routine (usage, credit, the trigger itself). The coordinator clears this by writing a fresh \`Last pass:\` line.\n\n${SIGNATURE}`;
  gh(['issue', 'comment', issue, '--body-file', '-'], message);
  console.log(`#${issue} stalled (${verdict.reason}); reported`);
}

function holdOne(issue, reason) {
  const { body } = readIssue(issue, 'body');
  if (!isHoldTicked(body)) gh(['issue', 'edit', issue, '--body-file', '-'], tickHold(body));
  gh(['issue', 'comment', issue, '--body-file', '-'], `**HOLD ticked by the main health check:** ${reason}\n\nThe owner or the coordinator clears it once \`main\` is green again.\n\n${SIGNATURE}`);
  console.log(`HOLD ticked on #${issue}: ${reason}`);
}

function heartbeat() {
  for (const issue of openTrainIssues()) heartbeatOne(issue);
}

function hold(reason) {
  if (!reason) throw new Error('hold needs a reason');
  for (const issue of openTrainIssues()) holdOne(issue, reason);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [command, ...rest] = process.argv.slice(2);
  if (command === 'heartbeat') heartbeat();
  else if (command === 'hold') hold(rest.join(' ').trim());
  else {
    console.error('usage: train-health.mjs heartbeat | hold <reason>');
    process.exit(2);
  }
}
