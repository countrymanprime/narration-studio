      lines.push('  repository: {');
      for (const [key] of REPOSITORY) lines.push(`    ${key}: ${singleQuote(brand.repository[key])},`);
      lines.push('  },', '  identity: {');
      for (const key of Object.keys(IDENTITY_KEYS)) lines.push(`    ${key}: ${singleQuote(brand.identity[key])},`);
