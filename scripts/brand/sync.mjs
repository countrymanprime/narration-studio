// A brand region in a Markdown or HTML file: `<!-- brand:<key> -->value<!-- /brand -->`. The key is a path into the derived
// brand (`name`, `repository.url`, `identity.projectFolder`); sync rewrites the value between the markers. A region is on one
// line and holds no backtick, so an example of one in a code span is left alone.
const REGION = /<!-- brand:([\w.]+) -->([^`\n]*?)<!-- \/brand -->/g;
const REGION_FILE = /\.(md|html)$/;

/** A value of the derived brand by its dotted key, or undefined. */
export function brandValue(brand, key) {
  const value = key.split('.').reduce((at, part) => (at && typeof at === 'object' ? at[part] : undefined), brand);
  return typeof value === 'string' ? value : undefined;
}

/** The text with every brand region's value rewritten; throws on an unknown key. */
export function renderRegions(text, brand, file = 'text') {
  return text.replace(REGION, (_, key) => {
    const value = brandValue(brand, key);
    if (value === undefined) throw new Error(`${file}: brand region "${key}" is not a brand value`);
    return `<!-- brand:${key} -->${value}<!-- /brand -->`;
  });
}

/** The files whose text differs from what the brand makes of them: [{ path, text }] with the text they should hold. */
export function staleFiles(root = REPOSITORY_ROOT, brand = loadBrand(root), files = listFiles(root)) {
  const stale = [];
  const read = (path) => (existsSync(join(root, path)) ? readFileSync(join(root, path), 'utf8') : null);
  for (const target of TARGETS) {
    const current = read(target.path);
    const text = target.render(brand, current);
    if (current !== text) stale.push({ path: target.path, text });
  }
  for (const path of files.filter((file) => REGION_FILE.test(file))) {
    const current = read(path);
    if (current === null || !current.includes('<!-- brand:')) continue;
    const text = renderRegions(current, brand, path);
    if (text !== current) stale.push({ path, text });
  }
  return stale;
}

/** Writes the stale files under root; returns their paths. */
export function sync(root = REPOSITORY_ROOT) {
  const stale = staleFiles(root);
  for (const { path, text } of stale) writeFileSync(join(root, path), text);
  return stale.map(({ path }) => path);
}

function main(args) {
  if (args.includes('--check')) {
    const stale = staleFiles().map(({ path }) => path);
    if (stale.length) {
      console.error(`Out of date with ${BRAND_FILE}; run \`pnpm run brand:sync\`:\n${stale.join('\n')}`);
      process.exitCode = 1;
    }
    return;
  }
  for (const path of sync()) console.log(`wrote ${path}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
