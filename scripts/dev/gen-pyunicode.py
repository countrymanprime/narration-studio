"""Write src/studio/desktop/internal/compare/pyunicode_gen.go from the running Python's own Unicode database.

The host's ports of the sidecars' text rules (internal/compare) must lowercase, split and match `\\w` exactly as
CPython 3.12 does, and Go's unicode package is a newer Unicode version (docs/research/sidecar-go-vs-python.md, the
traps). The tables are generated, never edited: `re`'s `\\w` for str patterns, `str.isspace`, `str.isprintable`,
`str.lower`'s and `str.casefold`'s mappings, and the Cased and Case_Ignorable sets of the final-sigma rule, which
CPython does not expose and which are probed through `str.lower` itself.

    uv run python scripts/dev/gen-pyunicode.py          # rewrite the file
    uv run python scripts/dev/gen-pyunicode.py --check  # exit 1 if the file is not what this Python writes

src/studio/libs/python/tests/test_pyunicode_tables.py runs --check, so a Python upgrade that moves Unicode fails there.
"""

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "src" / "studio" / "desktop" / "internal" / "compare" / "pyunicode_gen.go"
WORD = re.compile(r"\w")


def chars():
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        yield c, chr(c)


def ranges(pred):
    out, start, prev = [], None, None
    for c, ch in chars():
        if pred(ch):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
    if start is not None:
        out.append((start, prev))
    return out


def cased(ch):
    """Cased and not Case_Ignorable: a capital sigma after it alone lowercases to the final ς."""
    if ch == "Σ":  # cannot probe itself; U+03A3 is Cased (Lu) and not Case_Ignorable
        return True
    return (ch + "Σ").lower()[-1] == "ς"


def ignorable(ch):
    """Case_Ignorable: a sigma after "A" and it is still final, and it is not one of the cased ones."""
    if ch == "Σ":
        return False
    return ("A" + ch + "Σ").lower()[-1] == "ς" and not cased(ch)


def render():
    lines = [
        f"// Code generated by scripts/dev/gen-pyunicode.py from Python {sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}). DO NOT EDIT.",
        "",
        "package compare",
        "",
        f'// PyUnicodeVersion is the Unicode version of the Python that wrote these tables.\nconst PyUnicodeVersion = "{unicodedata.unidata_version}"',
        "",
    ]
    for name, about, pred in [
        ("pyWordRanges", "the code points re's \\w matches in a str pattern", lambda ch: WORD.match(ch) is not None),
        ("pySpaceRanges", "the code points str.isspace counts as space", lambda ch: ch.isspace()),
        ("pyCasedRanges", "the code points the final-sigma rule counts as cased", cased),
        ("pyIgnorableRanges", "the code points the final-sigma rule skips as case-ignorable", ignorable),
        ("pyPrintableRanges", "the code points str.isprintable counts as printable (what repr leaves unescaped)", lambda ch: ch.isprintable()),
    ]:
        lines.append(f"// {name} are {about}, as inclusive ranges in order.")
        lines.append(f"var {name} = [][2]rune{{")
        lines += [f"\t{{0x{a:X}, 0x{b:X}}}," for a, b in ranges(pred)]
        lines += ["}", ""]
    lines.append("// pyLowerMap is str.lower for every code point it changes, the final sigma aside.")
    lines.append("var pyLowerMap = map[rune]string{")
    for c, ch in chars():
        low = ch.lower()
        if low != ch:
            escaped = "".join(f"\\U{ord(x):08X}" for x in low)
            lines.append(f'\t0x{c:05X}: "{escaped}",')
    lines += ["}", ""]
    lines.append("// pyCasefoldMap is str.casefold for every code point it changes.")
    lines.append("var pyCasefoldMap = map[rune]string{")
    for c, ch in chars():
        folded = ch.casefold()
        if folded != ch:
            escaped = "".join(f"\\U{ord(x):08X}" for x in folded)
            lines.append(f'\t0x{c:05X}: "{escaped}",')
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv):
    text = render()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is not what Python {sys.version_info.major}.{sys.version_info.minor} writes: run scripts/dev/gen-pyunicode.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
