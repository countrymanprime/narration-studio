// Gathers every step only the owner can do and prints it as Markdown ready to paste as comments on #992 (Owner queue).
// Read-only: it only calls `gh api` GET routes. Re-run it any time; slices that merge later add steps. Nothing is written to the repo.
//
//   node scripts/dev/owner-qa-list.mjs --dry-run          print the whole report from the live slice issues
//   node scripts/dev/owner-qa-list.mjs --area reaper      print one area (app reaper audacity hardware manuscript other)
//   node scripts/dev/owner-qa-list.mjs --no-baseline      leave out the steps the PRDs name that no slice line carries
//   node scripts/dev/owner-qa-list.mjs --help
//
// Sources: the `Owner steps (to #992):` line of each issue labelled `slice`, and the BASELINE below (steps the PRDs name).
// A body whose line cannot be parsed is listed under "Needs a human read" with its issue number, never skipped.
// An owner step is never a merge gate (D65); an unfinished one is waived by the owner's comment on #992, never silently.
// Tested by scripts/ci/owner-qa-list.test.mjs.

import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

export const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n';

