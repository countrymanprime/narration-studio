const FIELD = /^\s*(?:[-*]\s*)?Owner steps \(to #992\):[ \t]*(.*)$/;
const LABEL = /^[A-Z][A-Za-z ()#/]{1,30}:/;

/** The steps in a slice body: `{status: 'steps' | 'none' | 'unparsed', steps}`. The last unquoted field wins. */
export function parseOwnerSteps(body) {
  const lines = String(body ?? '').split(/\r?\n/);
  let start = -1;
  lines.forEach((line, i) => { if (FIELD.test(line)) start = i; });
  if (start < 0) return { status: 'unparsed', steps: [] };
  const parts = [FIELD.exec(lines[start])[1].trim()];
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim() || line.startsWith('```') || /^#/.test(line) || LABEL.test(line)) break;
    parts.push(line.trim());
  }
  const text = parts.filter(Boolean).join(' ').trim();
  if (!text || /^<[^>]*>$/.test(text)) return { status: 'unparsed', steps: [] };
  if (/^none(?![\w-])/i.test(text)) return { status: 'none', steps: [] };
  if (/^\(1\)\s/.test(text) && /\(2\)\s/.test(text)) {
    const steps = text.split(/\s*\(\d+\)\s+/).map((s) => s.replace(/[;\s]+$/, '').trim()).filter(Boolean);
    return { status: 'steps', steps };
  }
  return { status: 'steps', steps: [text] };
}

/** Which area's equipment a step needs. */
export function classifyArea(text) {
  if (/pedal|audio interface|\bmicrophone\b|real record|\bbooth\b/i.test(text)) return 'hardware';
  if (/manuscript|extraction/i.test(text)) return 'manuscript';
  if (/audacity/i.test(text)) return 'audacity';
  if (/reaper|ctrl\+z/i.test(text)) return 'reaper';
  if (/shift\+f10|webview|built app|windows|menu key/i.test(text)) return 'app';
  return 'other';
}

function sliceIdentity(issue) {
  const body = String(issue.body ?? '');
  const id = /^id:\s*(SN-[A-Z]+\d+\w*)/m.exec(body)?.[1] ?? `#${issue.number}`;
  const prd = /\bslice (SN[A-Z]+)-/.exec(body)?.[1] ?? issue.labels?.map((l) => /^prd:(.+)$/.exec(l.name ?? l)?.[1]).find(Boolean) ?? 'unknown';
  return { id, prd };
}

function runbookLinks(text, area) {
  const named = [...text.matchAll(/docs\/[\w./-]+\.md/g)].map((m) => m[0]);
  if (!named.length && RUNBOOKS[area]) named.push(RUNBOOKS[area]);
  return [...new Set(named)].map((path) => `[${path.split('/').pop()}](${LINK_BASE}${path})`);
}

function section({ title, slice, text, area, run }) {
  const links = runbookLinks(`${text} ${run ?? ''}`, area);
  const runLine = [run, links.length && !run?.includes('](') ? `Runbook: ${links.join(', ')}.` : ''].filter(Boolean).join(' ') || 'The step text above; the runbook, if any, holds the commands.';
  return [
    `### ${title}`,
    '',
    `Slice: ${slice}. ${text}`,
    '',
    `**Run:** ${runLine}`,
    '',
    '**Pass:** the result matches what the slice describes. Reply on this comment with the date and what you saw.',
    '',
    '**Fail:** it differs, or the app or DAW misbehaves. Reply with what you saw and any log.',
    '',
    `**On a fail:** open an issue titled \`fix: owner QA failed: ${title}\`, label it \`studio-next\`, and link this comment. Or waive the step by commenting "waived: <reason>"; it never blocks a merge (D65).`,
    '',
  ].join('\n');
}

/** The report: one `##` per area, one `###` per step, then the unread bodies. `options.baseline: false` leaves out BASELINE. */
export function renderReport(issues, options = {}) {
  const byArea = Object.fromEntries(Object.keys(AREAS).map((key) => [key, []]));
  const unread = [];
  for (const issue of issues) {
    const parsed = parseOwnerSteps(issue.body);
    if (parsed.status === 'unparsed') { unread.push(issue); continue; }
    const { id, prd } = sliceIdentity(issue);
    for (const text of parsed.steps) {
      const area = classifyArea(text);
      byArea[area].push(section({ title: `${id} (#${issue.number})`, slice: `${id}, ${prd}, #${issue.number}${issue.state === 'closed' ? ' (closed)' : ''}`, text, area }));
    }
  }
  if (options.baseline !== false) {
    for (const item of BASELINE) {
      byArea[item.area].push(section({ title: `${item.code}: ${item.step.split(/[:.]/)[0]}`, slice: `${item.code} (from the PRDs)`, text: item.step, area: item.area, run: item.run }));
    }
  }
  const only = options.area;
  const out = ['# Owner QA list (SN-C2)', '', 'Steps only the owner can do. None blocks a merge (D65); clear each one or waive it by comment. Re-run `node scripts/dev/owner-qa-list.mjs` for the current list.', ''];
  for (const [key, label] of Object.entries(AREAS)) {
    if ((only && only !== key) || !byArea[key].length) continue;
    out.push(`## ${label}`, '', ...byArea[key]);
  }
  if (!only && unread.length) {
    out.push('## Needs a human read', '', 'The `Owner steps (to #992)` line of these issues could not be parsed. Read the issue.', '');
    for (const issue of unread) out.push(`- #${issue.number} ${issue.title ?? ''}`.trimEnd());
    out.push('');
  }
  return out.join('\n').replace(/\n+$/, '') + FOOTER;
}

/** Wraps a `gh` runner so only `gh api` GET routes pass. */
export function guardedGh(run) {
  return (args) => {
    const write = args.some((a) => /^(-X|--method|-f|-F|--field|--raw-field|--input)$/.test(a) && !(/^(-X|--method)$/.test(a) && /^GET$/i.test(args[args.indexOf(a) + 1] ?? '')));
    if (args[0] !== 'api' || write) throw new Error(`read-only: refusing \`gh ${args.join(' ')}\``);
    return run(args);
  };
}

/** Every issue labelled `slice` (open and closed), a page of 100 at a time. */
export function fetchSlices(gh) {
  const issues = [];
  for (let page = 1; ; page++) {
    const batch = JSON.parse(gh(['api', `repos/{owner}/{repo}/issues?labels=slice&state=all&per_page=100&page=${page}`]));
    issues.push(...batch.filter((issue) => !issue.pull_request));
    if (batch.length < 100) return issues;
  }
}

const runGh = (args) => execFileSync('gh', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

function main(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(readFileHeader());
    return 0;
  }
  const areaAt = argv.indexOf('--area');
  const area = areaAt >= 0 ? argv[areaAt + 1] : undefined;
  if (area && !(area in AREAS)) { console.error(`unknown area "${area}"; one of ${Object.keys(AREAS).join(', ')}`); return 2; }
  try {
    console.log(renderReport(fetchSlices(guardedGh(runGh)), { area, baseline: !argv.includes('--no-baseline') }));
  } catch (error) {
    console.error(error.code === 'ENOENT' ? 'the gh CLI is not installed' : error.message);
    return 1;
  }
  return 0;
}

function readFileHeader() {
  return [
    'owner-qa-list: print the owner steps for #992 as Markdown comments (read-only, re-runnable).',
    '  --dry-run      print the report (the default; the script never writes)',
    `  --area <name>  one of ${Object.keys(AREAS).join(', ')}`,
    '  --no-baseline  leave out the PRD steps no slice line carries',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exitCode = main(process.argv.slice(2));
