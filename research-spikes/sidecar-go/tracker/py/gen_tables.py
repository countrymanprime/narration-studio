"""Generate go/unitables_gen.go from the running Python's Unicode database (15.0 for CPython 3.12).

Tables: \\w (re, str patterns), str.lower() mapping, the Final_Sigma context's Cased / Case_Ignorable
(probed through str.lower itself, since CPython does not expose them), and str.split() whitespace.
"""

import re
import sys
import unicodedata

WORD = re.compile(r"\w")


def chars():
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        yield c, chr(c)


def ranges(pred):
    out, start, prev = [], None, None
    for c, ch in chars():
        if pred(ch):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
    if start is not None:
        out.append((start, prev))
    return out


def cased_not_ign(ch):  # "cΣ" lowers to final sigma iff ch is Cased and not Case_Ignorable
    if ch == "Σ":  # cannot probe itself; U+03A3 is Cased (Lu) and not Case_Ignorable
        return True
    return (ch + "Σ").lower()[-1] == "ς"


def ign(ch):  # "AcΣ" -> ς iff ignorable or cased; minus the cased-only ones
    if ch == "Σ":
        return False
    return ("A" + ch + "Σ").lower()[-1] == "ς" and not cased_not_ign(ch)


def emit(fh, name, rs):
    fh.write(f"var {name} = [][2]rune{{\n")
    for a, b in rs:
        fh.write(f"\t{{0x{a:X}, 0x{b:X}}},\n")
    fh.write("}\n\n")


def main(path):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"// Code generated by gen_tables.py from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). DO NOT EDIT.\n\npackage main\n\n")
        fh.write(f'const pyUnicodeVersion = "{unicodedata.unidata_version}"\n\n')
        emit(fh, "pyWordRanges", ranges(lambda ch: WORD.match(ch) is not None))
        emit(fh, "pyCasedRanges", ranges(cased_not_ign))
        emit(fh, "pyIgnorableRanges", ranges(ign))
        emit(fh, "pySpaceRanges", ranges(lambda ch: ch.isspace()))
        fh.write("var pyLowerMap = map[rune]string{\n")
        for c, ch in chars():
            low = ch.lower()
            if low != ch:
                fh.write("\t0x%X: %s,\n" % (c, '"' + "".join("\\U%08X" % ord(x) for x in low) + '"'))
        fh.write("}\n")


if __name__ == "__main__":
    main(sys.argv[1])
