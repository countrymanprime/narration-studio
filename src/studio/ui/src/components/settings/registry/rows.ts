/** The models a background check may be told to use: a large one costs minutes of every processor it is given. */
const HEAVY_MODELS = new Set(['medium', 'large-v3-turbo', 'large-v3']);
const heavyModel = (value: string): string | undefined =>
  HEAVY_MODELS.has(value) ? 'A large model makes every background check much slower and keeps this computer busy for longer.' : undefined;
/** This computer's processors as the browser reports them; the host plans with its own count. */
const processorCount = (): number => (typeof navigator !== 'undefined' && navigator.hardwareConcurrency) || 4;
const LIVE_MODEL: Record<string, OptionNote> = {
  tiny: { label: 'Tiny', asset: { kind: { followRow: 'stt.live' }, id: 'tiny' } },
  small: { label: 'Small', asset: { kind: { followRow: 'stt.live' }, id: 'small' } },
};

/** The asset a choice of `row` points at, or undefined; `kindOf` resolves a kind that follows another row. */
export function assetOfOption(note: OptionNote | undefined, kindOf: (rowId: string) => string): { kind: string; id: string } | undefined {
  const ref: AssetRef | undefined = note?.asset;
  if (!ref) return undefined;
  return { kind: typeof ref.kind === 'string' ? ref.kind : kindOf(ref.kind.followRow), id: ref.id };
}

const NOT_REAPER_PATH = 'This is not the path to reaper.exe. Use the full path, such as C:\\Program Files\\REAPER\\reaper.exe.';

/** A REAPER path is a full path whose last part is `reaper` or `reaper.exe` (the host does not check); empty means "find it on its own". */
export function reaperPathProblem(value: string): string | undefined {
  const path = value.trim();
  return path === '' || /[\\/]reaper(\.exe)?$/i.test(path) ? undefined : NOT_REAPER_PATH;
}

