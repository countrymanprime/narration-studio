// The retry column of the interaction feedback catalog (docs/architecture/interaction-feedback.md#retry): for every error toast, whether
// the toast offers Retry, and why not when it does not. `interactionFeedback.retry.test.ts` finds the sites with the TypeScript parser.
//
// A site is `<file under src/studio/ui>#<n>`, the n-th error-toast call in that file, in source order
// (`notify(_, 'error')`, `overlay.toast(_, { tone: 'error' })` and `useErrorToast(_)`). Adding or removing one renumbers the ones after it.
//
// Retry belongs on a failure whose repeat is safe (a save of the same value, a read) and whose trigger the narrator cannot press again.
// It never belongs on record, delete, duplicate, import, a DAW edit or a refusal.

type RetryVerdict = 'yes' | 'no' | 'n/a';
export type RetryJudgment = { retry: RetryVerdict; reason: string };

const yes = (reason: string): RetryJudgment => ({ retry: 'yes', reason });
const no = (reason: string): RetryJudgment => ({ retry: 'no', reason });
const na = (reason: string): RetryJudgment => ({ retry: 'n/a', reason });

