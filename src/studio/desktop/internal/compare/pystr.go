package compare

import (
	"strings"
	"unicode"
)

// IsPySpace is Python's str.isspace for one code point, what str.split(),
// str.strip() and the re module's \s use. Unlike unicode.IsSpace it counts
// U+001C to U+001F (the information separators) as space.
func IsPySpace(r rune) bool {
	switch r {
	case ' ', '\t', '\n', '\v', '\f', '\r', 0x1c, 0x1d, 0x1e, 0x1f, 0x85, 0xa0, 0x1680,
		0x2028, 0x2029, 0x202f, 0x205f, 0x3000:
		return true
	}
	return r >= 0x2000 && r <= 0x200a
}

// PySplit is Python's str.split() with no separator.
func PySplit(s string) []string { return strings.FieldsFunc(s, IsPySpace) }

// PyStrip is Python's str.strip() with no argument.
func PyStrip(s string) string { return strings.TrimFunc(s, IsPySpace) }

// pyKeepsCase lists the code points CPython 3.12 (Unicode 15.0) does not
// lowercase but Go's newer Unicode tables do: letters added in Unicode 16 and
// 17, generated by comparing str.lower with strings.ToLower over every code
// point.
func pyKeepsCase(r rune) bool {
	switch r {
	case 0x1c89, 0xa7cb, 0xa7cc, 0xa7ce, 0xa7d2, 0xa7d4, 0xa7da, 0xa7dc:
		return true
	}
	return r >= 0x10d50 && r <= 0x10d65 || r >= 0x16ea0 && r <= 0x16eb8
}

// PyLower is Python 3.12's str.lower: Go's lowercasing with the differences
// above, the one unconditional multi-rune mapping (U+0130 to "i̇") and the
// final-sigma rule (a capital sigma that ends a word lowercases to ς). The
// sigma rule's "cased" and "case-ignorable" tests use Go's Unicode tables, so
// a letter newer than Unicode 15 beside a sigma may still differ.
func PyLower(s string) string {
	runes := []rune(s)
	var out strings.Builder
	out.Grow(len(s))
	for i, r := range runes {
		switch {
		case r == 0x130:
			out.WriteString("i̇")
		case r == 'Σ':
			if finalSigma(runes, i) {
				out.WriteRune('ς')
			} else {
				out.WriteRune('σ')
			}
		case pyKeepsCase(r):
			out.WriteRune(r)
		default:
			out.WriteRune(unicode.ToLower(r))
		}
	}
	return out.String()
}

// finalSigma is CPython's handle_capital_sigma: a cased letter comes before
// position i and none after it, skipping case-ignorable runes both ways.
func finalSigma(runes []rune, i int) bool {
	j := i - 1
	for j >= 0 && caseIgnorable(runes[j]) {
		j--
	}
	if j < 0 || !cased(runes[j]) {
		return false
	}
	k := i + 1
	for k < len(runes) && caseIgnorable(runes[k]) {
		k++
	}
	return k == len(runes) || !cased(runes[k])
}

func cased(r rune) bool {
	return unicode.IsUpper(r) || unicode.IsLower(r) || unicode.IsTitle(r) ||
		unicode.Is(unicode.Other_Lowercase, r) || unicode.Is(unicode.Other_Uppercase, r)
}

func caseIgnorable(r rune) bool {
	switch r {
	case '\'', '.', ':', '^', '`', 0xad, 0xb7, 0x2018, 0x2019, 0x2024, 0x2027:
		return true
	}
	return unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf, unicode.Lm, unicode.Sk)
}
