package dawportdoc

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/countrymanprime/narration-utils/shell/internal/dawport"
	"github.com/countrymanprime/narration-utils/shell/internal/dawport/audacity"
	"github.com/countrymanprime/narration-utils/shell/internal/dawport/reaper"
)

// The DAW reference (docs/reference/daw) is pinned to the port's declarations: matrix.md is generated from them and
// capabilities.md must have exactly one section per capability, so a capability or level cannot change without the reference
// changing. Run the tests with UPDATE_DAW_DOCS=1 to rewrite matrix.md after a deliberate change, and commit the diff.

const updateDocsEnv = "UPDATE_DAW_DOCS"

// audacity4Cell is the Audacity 4.x column. It is not a declaration: Audacity 4.0.0 ships without the scripting pipe, so the adapter
// reaches nothing there (docs/reference/daw/audacity-4.md). It is a fixed phrase, not derived from code.
const audacity4Cell = "Not reachable"

var capabilityHeading = regexp.MustCompile("(?m)^### `([a-z_]+)`")

func referenceDir(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "pnpm-workspace.yaml")); err == nil {
			return filepath.Join(dir, "docs", "reference", "daw")
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("no pnpm-workspace.yaml above the test directory")
		}
		dir = parent
	}
}

func levelCell(l dawport.Level) string {
	switch l {
	case dawport.Supported:
		return "Supported"
	case dawport.Experimental:
		return "Experimental"
	case dawport.NotYetAvailable:
		return "Not yet available"
	default:
		return "Unsupported"
	}
}

func needsCell(n dawport.Needs) string {
	switch n {
	case dawport.NeedsBridge:
		return "A bridge, answering or not"
	case dawport.NeedsNothing:
		return "Nothing (works offline)"
	default:
		return "Engine answering"
	}
}

// renderMatrix is matrix.md, built only from the specs and the two adapters' static declarations.
func renderMatrix() string {
	reaperLevels := reaper.Declaration().Declares()
	audacityLevels := (&audacity.Adapter{}).Declares()

	var b strings.Builder
	b.WriteString("<!-- Generated by TestDAWReferenceMatrix in apps/desktop/internal/dawport/dawportdoc. Do not edit: run that test with UPDATE_DAW_DOCS=1. -->\n\n")
	b.WriteString("# DAW capability matrix\n\n")
	b.WriteString("What each engine declares for each capability today. The levels are the adapters' static declarations ")
	b.WriteString("(`Declares()`); what a narrator can use at a given moment is the resolver's answer, which also depends on the engine ")
	b.WriteString("answering and on the `DAW.capability.<name>` setting. What each capability returns, and what has been checked, is in ")
	b.WriteString("[capabilities](capabilities.md). The Audacity 4.x column is a fixed statement, not a declaration ([Audacity 4](audacity-4.md)).\n\n")
	b.WriteString("| Capability | Role | Needs | REAPER 7.x | Audacity 3.x | Audacity 4.x |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, spec := range dawport.Capabilities() {
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s | %s |\n",
			spec.Capability, spec.Role.Name(), needsCell(spec.Needs),
			levelCell(reaperLevels[spec.Capability]), levelCell(audacityLevels[spec.Capability]), audacity4Cell)
	}
	return b.String()
}

func TestDAWReferenceMatrix(t *testing.T) {
	path := filepath.Join(referenceDir(t), "matrix.md")
	want := renderMatrix()
	if os.Getenv(updateDocsEnv) != "" {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with %s=1 to create it)", err, updateDocsEnv)
	}
	if string(got) != want {
		t.Errorf("docs/reference/daw/matrix.md is out of date with the adapters' declarations; run this test with %s=1 and commit the diff", updateDocsEnv)
	}
}

func TestDAWReferenceHasOneSectionPerCapability(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join(referenceDir(t), "capabilities.md"))
	if err != nil {
		t.Fatal(err)
	}
	var found []string
	for _, m := range capabilityHeading.FindAllStringSubmatch(string(raw), -1) {
		found = append(found, m[1])
	}
	var want []string
	for _, spec := range dawport.Capabilities() {
		want = append(want, string(spec.Capability))
	}
	if strings.Join(found, ",") != strings.Join(want, ",") {
		t.Errorf("capabilities.md sections, in order:\n got  %v\n want %v\n(one \"### `name`\" section per capability, in catalog order)", found, want)
	}
}
