const uiRoot = join(__dirname, '..');
const componentsRoot = join(uiRoot, 'src', 'components');
const primitivesDir = join('src', 'components', 'primitives');
const SOURCE = /\.tsx?$/;
const NOT_UNDER_TEST = /\.test\.tsx?$/;
const ICON_MODULE = /^@fortawesome\/free-[a-z]+-svg-icons$/;
const COMPONENT_MODULE = '@fortawesome/react-fontawesome';

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(path);
    return SOURCE.test(entry.name) && !NOT_UNDER_TEST.test(entry.name) ? [path] : [];
  });
}

// Imported names that draw an icon: `FontAwesomeIcon`, and every named import from a free icon package. A type-only import
// (`IconDefinition`) draws nothing, and a namespace import counts once.
function scan(source: string, fileName = 'probe.tsx'): number {
  const file = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, fileName.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  let count = 0;
  for (const statement of file.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue;
    const module = statement.moduleSpecifier.text;
    const clause = statement.importClause;
    if (clause === undefined || clause.isTypeOnly) continue;
    const bindings = clause.namedBindings;
    if (ICON_MODULE.test(module)) {
      if (bindings !== undefined && ts.isNamedImports(bindings)) count += bindings.elements.filter((element) => !element.isTypeOnly).length;
      else if (bindings !== undefined) count += 1;
      if (clause.name !== undefined) count += 1;
    } else if (module === COMPONENT_MODULE && bindings !== undefined && ts.isNamedImports(bindings)) {
      count += bindings.elements.filter((element) => !element.isTypeOnly && (element.propertyName ?? element.name).text === 'FontAwesomeIcon').length;
    }
  }
  return count;
}

const counts: Record<string, number> = {};
for (const path of sourceFiles(componentsRoot)) {
  const file = relative(uiRoot, path);
  if (file.startsWith(primitivesDir + sep)) continue;
  const count = scan(readFileSync(path, 'utf8'), file);
  if (count > 0) counts[file.split(sep).join('/')] = count;
}

describe('direct Font Awesome imports only fall (ADR 0761)', () => {
  test('direct-imports-only-fall: no file gained one', () => {
    const grew = Object.entries(counts).filter(([file, count]) => count > (CEILING[file] ?? 0));
    expect(
      grew,
      'a component outside primitives imports an icon directly: use <Icon name="..."/> or <IconButton action="..."/> and add a row to src/icons.catalog.ts',
    ).toEqual([]);
  });

  test('direct-imports-only-fall: no ceiling is above the real count', () => {
    const stale = Object.entries(CEILING).filter(([file, allowed]) => (counts[file] ?? 0) < allowed);
    expect(stale, 'a file lost a direct icon import: lower its ceiling (delete the entry at zero)').toEqual([]);
  });

  test('the primitives are not counted', () => {
    expect(Object.keys(counts).filter((file) => file.includes('/primitives/'))).toEqual([]);
  });

  test('the scan sees each way of importing an icon (a bad fixture per form)', () => {
    expect(scan(`import { FontAwesomeIcon } from '@fortawesome/react-fontawesome';`)).toBe(1);
    expect(scan(`import { FontAwesomeIcon as FA } from '@fortawesome/react-fontawesome';`)).toBe(1);
    expect(scan(`import { faPen, faTrash } from '@fortawesome/free-solid-svg-icons';`)).toBe(2);
    expect(scan(`import { faPen as pen } from '@fortawesome/free-regular-svg-icons';`)).toBe(1);
    expect(scan(`import { faGithub } from '@fortawesome/free-brands-svg-icons';`)).toBe(1);
    expect(scan(`import * as solid from '@fortawesome/free-solid-svg-icons';`)).toBe(1);
  });

  test('the scan ignores what draws nothing', () => {
    expect(scan(`import type { IconDefinition } from '@fortawesome/fontawesome-svg-core';`)).toBe(0);
    expect(scan(`import { type IconProp } from '@fortawesome/fontawesome-svg-core';`)).toBe(0);
    expect(scan(`import type { FontAwesomeIcon } from '@fortawesome/react-fontawesome';`)).toBe(0);
    expect(scan(`// import { faPen } from '@fortawesome/free-solid-svg-icons';\nconst a = "import { faPen } from '@fortawesome/free-solid-svg-icons'";`)).toBe(
      0,
    );
    expect(scan(`import { Icon } from '../primitives/Icon';`)).toBe(0);
  });
});

